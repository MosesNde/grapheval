#!/usr/bin/env python3
"""
build_cwe_corpus.py — assemble a real-CVE, CWE-family-labelled corpus from the
CPGs that already exist on disk. No LLM-generated samples.

INPUTS (all already present, nothing is regenerated)
    /home/moses/CPGExplainer/dots/{bigvul,cvefixes,devign}/**.dot   ~80k CPGs
    /home/moses/CPGExplainer/data/{bigvul,cvefixes,devign}_meta.json
    /home/moses/CPGExplainer/data/MSR_data_cleaned.csv    (BigVul raw)
    /home/moses/CPGExplainer/data/CVEfixes.db             (CVEfixes raw)

WHAT IT ADDS
    The existing *_meta.json files record dot paths but not the fields a
    leakage-resistant evaluation needs. This recovers, per sample:
        cwe / family    label for the fine-grained task
        repo, commit    grouping keys for repository- and commit-disjoint splits
        pair_id         groups a vulnerable function with its patched twin
        year            for chronological splitting
        provenance      corpus of origin, so any train/test imbalance is visible

OUTPUT
    data/cwe_corpus.jsonl   one record per CPG
    data/cwe_corpus_report.json   support per family, per corpus, unmapped counts

BigVul's sample_id is "bigvul-{i}" where i is the csv.DictReader record ordinal
from build_dataset_bigvul.py. That loop is replayed exactly here -- same reader,
same increment order -- so the ordinals line up. Do not "optimise" this into a
pandas read; the ordinals would shift and every label would be silently wrong.

Run:
    python3 build_cwe_corpus.py            # full build, ~15-25 min (CSV pass)
    python3 build_cwe_corpus.py --report-only   # re-report from existing jsonl
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import re
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cwe_taxonomy import to_family, FAMILIES  # noqa: E402

CPGX = Path("/home/moses/CPGExplainer")
DATA = CPGX / "data"
OUT_DIR = Path(__file__).resolve().parent.parent / "data"
OUT_JSONL = OUT_DIR / "cwe_corpus.jsonl"
OUT_REPORT = OUT_DIR / "cwe_corpus_report.json"

_YEAR_RE = re.compile(r"CVE-(\d{4})-")


def _year(cve: object) -> int | None:
    m = _YEAR_RE.search(str(cve or ""))
    return int(m.group(1)) if m else None


# ─────────────────────────────────────────────────────────────────────────────
# BigVul
# ─────────────────────────────────────────────────────────────────────────────
def bigvul_index() -> dict[int, dict]:
    """Replay build_dataset_bigvul.py's reader loop to map ordinal -> fields."""
    csv.field_size_limit(2**31 - 1)
    path = DATA / "MSR_data_cleaned.csv"
    idx: dict[int, dict] = {}
    with open(path, newline="", encoding="utf-8", errors="replace") as f:
        reader = csv.DictReader(f)
        i = -1
        while True:
            i += 1
            try:
                row = next(reader)
            except StopIteration:
                break
            except csv.Error:
                continue
            if row.get("lang", "").strip() not in ("C", "C++"):
                continue
            idx[i] = {
                "cwe": (row.get("CWE ID") or "").strip(),
                "cve": (row.get("CVE ID") or "").strip(),
                "repo": (row.get("project") or "").strip(),
                "commit": (row.get("commit_id") or "").strip(),
                "func_name": (row.get("func_name") or "").strip(),
            }
            if i % 200000 == 0:
                print(f"  [bigvul] scanned {i} rows", flush=True)
    print(f"  [bigvul] indexed {len(idx)} C/C++ rows")
    return idx


def load_bigvul(records: list[dict]) -> None:
    """BigVul VULNERABLE functions, regenerated by regen_cpgs.py.

    v2 graphs use per-function language detection: 4,708 of these 10,763 are
    C++ that the original build handed to Joern's C frontend, which emitted a
    9-node "<global>" stub. Stub rate falls 43.7% -> 8.4%. The non-vulnerable
    side is no longer loaded here at all -- see load_bigvul_safe_ext().
    """
    meta = json.loads((DATA / "bigvul_v2_meta.json").read_text())["samples"]
    idx = bigvul_index()
    miss = 0
    for s in meta:
        if s.get("status") != "ok":
            continue
        try:
            ordinal = int(str(s["sample_id"]).split("-")[-1])
        except ValueError:
            continue
        info = idx.get(ordinal)
        if info is None:
            miss += 1
            continue
        label = int(s.get("label", 0))
        # NOTE: BigVul has no pairs to preserve. build_dataset_bigvul.py takes
        # func_before from vul==1 rows and func_after from vul==0 rows, so a
        # vulnerable function's patched twin is never itself converted to a CPG
        # -- verified: all 32,289 records sit in pair groups of size 1. The
        # grouping that matters here is the COMMIT: 530 BigVul commits hold both
        # a vulnerable and a non-vulnerable function (64.9% of records), and
        # make_splits.py unions on commit for exactly that reason.
        #
        # func_name is unavailable: MSR_data_cleaned.csv has no such column, so
        # it is blank for every BigVul record and cannot be used for grouping.
        records.append({
            "sample_id": s["sample_id"],
            "dot_path": s.get("dot_path", ""),
            "label": label,
            "cwe": info["cwe"] if label == 1 else "",
            "family": to_family(info["cwe"]) if label == 1 else None,
            "repo": info["repo"],
            "commit": info["commit"],
            "pair_id": f"bigvul-pair-{ordinal}",
            "cve": info["cve"],
            "year": _year(info["cve"]),
            "func_name": info["func_name"] or s.get("func_name", ""),
            "provenance": "bigvul",
            "stub": bool(s.get("stub")),
            "ext": s.get("ext"),
        })
    if miss:
        print(f"  [bigvul] {miss} samples had no matching CSV ordinal")


def load_bigvul_safe_ext(records: list[dict]) -> None:
    """The non-vulnerable BigVul functions the original build skipped.

    build_dataset_bigvul.py capped the safe pool with `safe_records[:max_safe]`
    -- a prefix, not a sample -- which left 221 of 287 vulnerability-bearing
    repositories with NO safe function at all. Chrome, Android, ImageMagick and
    php-src were 100% vulnerable in the corpus, so "which repository is this"
    became a usable proxy for the label inside training.

    build_bigvul_safe.py re-samples per repository (see its header) and these
    are its outputs. Metadata comes straight from the CSV row, so no join is
    needed. Every record is non-vulnerable by construction: no cwe, no family.
    """
    path = DATA / "safe_ext_v2_meta.json"
    if not path.exists():
        print("  [bigvul-safe-ext] not present -- run build_bigvul_safe.py")
        return
    meta = json.loads(path.read_text())["samples"]
    n = 0
    for s in meta:
        if s.get("status") != "ok":
            continue
        records.append({
            "sample_id": s["sample_id"],
            "dot_path": s.get("dot_path", ""),
            "label": 0,
            "cwe": "",
            "family": None,
            "repo": s.get("repo", ""),
            "commit": s.get("commit", ""),
            # Unique per function: these are untouched functions, not the
            # patched half of a pair, so there is nothing to group them with.
            "pair_id": s["sample_id"],
            "cve": s.get("cve", ""),
            "year": _year(s.get("cve")),
            "func_name": "",
            "provenance": "bigvul",
            "stub": bool(s.get("stub")),
            "ext": s.get("ext"),
        })
        n += 1
    print(f"  [bigvul-safe-ext] {n} re-sampled non-vulnerable functions")


# ─────────────────────────────────────────────────────────────────────────────
# CVEfixes
# ─────────────────────────────────────────────────────────────────────────────
def cvefixes_index() -> dict[str, dict]:
    """method_change_id -> {cwe, repo, commit, cve, year}."""
    conn = sqlite3.connect(f"file:{DATA/'CVEfixes.db'}?mode=ro", uri=True)
    rows = conn.execute("""
        SELECT mc.method_change_id, cc.cwe_id, cm.repo_url, cm.hash, fx.cve_id
        FROM method_change mc
        JOIN file_change fc ON mc.file_change_id = fc.file_change_id
        JOIN commits     cm ON fc.hash          = cm.hash
        JOIN fixes       fx ON cm.hash          = fx.hash
        LEFT JOIN cwe_classification cc ON fx.cve_id = cc.cve_id
        WHERE fc.programming_language IN ('C','C++')
    """).fetchall()
    conn.close()

    out: dict[str, dict] = {}
    for mcid, cwe, repo, commit, cve in rows:
        rec = out.setdefault(str(mcid), {
            "cwe": "", "repo": repo or "", "commit": commit or "",
            "cve": cve or "", "cwes": []})
        if cwe:
            rec["cwes"].append(str(cwe))
    # A CVE may carry several CWEs; keep the first that maps to a family so the
    # choice is deterministic and auditable rather than arbitrary.
    for rec in out.values():
        rec["cwe"] = next((c for c in rec["cwes"] if to_family(c)),
                          rec["cwes"][0] if rec["cwes"] else "")
        rec.pop("cwes")
    print(f"  [cvefixes] indexed {len(out)} method_change_ids")
    return out


def load_cvefixes(records: list[dict]) -> None:
    """CVEfixes pairs, regenerated by regen_cpgs.py.

    The v2 manifest already applies the same dedup rule the old loader did
    (one pair per vulnerable method, numerically lowest safe id), so the pairs
    arrive pre-resolved and each carries its own dot path. Only the CWE and
    repository/commit metadata still needs the database join.

    Language detection cut the stub rate from 23.5%/20.3% to 8.5%/8.6%.
    """
    meta = json.loads((DATA / "cvefixes_v2_meta.json").read_text())["samples"]
    idx = cvefixes_index()
    miss = 0
    for s in meta:
        if s.get("status") != "ok":
            continue
        pair = s.get("pair", "")
        parts = pair.split("-")
        if len(parts) != 3 or not (parts[1].isdigit() and parts[2].isdigit()):
            continue
        vuln_id = parts[1]
        info = idx.get(vuln_id)
        if info is None:
            miss += 1
            continue
        label = int(s["label"])
        fam = to_family(info["cwe"]) if label == 1 else None
        records.append({
            "sample_id": s["sample_id"],
            "dot_path": s["dot_path"],
            "label": label,
            "cwe": info["cwe"] if label == 1 else "",
            "family": fam,
            "repo": info["repo"],
            "commit": info["commit"],
            # The vulnerable function and its patched twin share one pair_id so
            # a grouped splitter can never place a function in train and its own
            # fix in test -- the most direct leak in patch-derived corpora.
            "pair_id": f"cvefixes-pair-{vuln_id}",
            "cve": info["cve"],
            "year": _year(info["cve"]),
            "func_name": "",
            "provenance": "cvefixes",
            "stub": bool(s.get("stub")),
            "ext": s.get("ext"),
        })
    if miss:
        print(f"  [cvefixes] {miss} samples had no DB match")


# ─────────────────────────────────────────────────────────────────────────────
# Devign — binary labels only, no CWE. Real non-vulnerable pool.
# ─────────────────────────────────────────────────────────────────────────────
def load_devign(records: list[dict]) -> None:
    meta = json.loads((DATA / "devign_meta.json").read_text())["samples"]
    for s in meta:
        if s.get("status") != "ok":
            continue
        records.append({
            "sample_id": s["sample_id"],
            "dot_path": s.get("dot_path", ""),
            "label": int(s.get("label", 0)),
            "cwe": "",
            "family": None,          # Devign carries no CWE: binary stage only
            "repo": s.get("project", ""),
            "commit": s.get("commit_id", ""),
            "pair_id": s.get("commit_id", "") or s["sample_id"],
            "cve": "",
            "year": None,
            "func_name": "",
            "provenance": "devign",
        })


# ─────────────────────────────────────────────────────────────────────────────
def _no_family_reason(r: dict) -> str:
    """Why a vulnerable sample carries no family. These are three different
    facts and collapsing them into one 'UNMAPPED' bucket hides which corpora
    are actually usable for the fine-grained task."""
    if r["provenance"] == "devign":
        return "NO_CWE_IN_CORPUS"        # Devign is binary by design
    cwe = str(r.get("cwe") or "").strip()
    if not cwe or re.match(r"NVD-CWE-(noinfo|Other)|^nan$", cwe, re.I):
        return "NO_CWE_ASSIGNED_BY_NVD"
    return "CWE_OUTSIDE_TAXONOMY"


def report(records: list[dict]) -> dict:
    vuln = [r for r in records if r["label"] == 1]
    fam = collections.Counter(r["family"] for r in vuln if r["family"])
    noreason = collections.Counter(_no_family_reason(r)
                                   for r in vuln if not r["family"])
    outside = collections.Counter(
        r["cwe"] for r in vuln
        if not r["family"] and _no_family_reason(r) == "CWE_OUTSIDE_TAXONOMY")

    # The fine-grained task only sees corpora that carry CWEs at all.
    typed = [r for r in vuln if r["provenance"] != "devign"]
    rep = {
        "n_total": len(records),
        "n_vulnerable": len(vuln),
        "prevalence": round(len(vuln) / max(1, len(records)), 4),
        "by_corpus": dict(collections.Counter(r["provenance"] for r in records)),
        "by_corpus_label": {
            f"{k[0]}/{'vuln' if k[1] else 'safe'}": v for k, v in
            sorted(collections.Counter(
                (r["provenance"], r["label"]) for r in records).items())},
        "family_support": dict(fam.most_common()),
        "no_family_reasons": dict(noreason.most_common()),
        "top_cwes_outside_taxonomy": outside.most_common(20),
        "n_typed_vulnerable": len(typed),
        "coverage_of_typed": round(sum(fam.values()) / max(1, len(typed)), 4),
        "n_distinct_repos": len({r["repo"] for r in records if r["repo"]}),
        "n_distinct_commits": len({r["commit"] for r in records if r["commit"]}),
        "n_distinct_pairs": len({r["pair_id"] for r in records if r["pair_id"]}),
        "families_over_500": [f for f, n in fam.items() if n >= 500],
    }

    # Stub rate BY LABEL is the check that matters. A gap here means "is this
    # graph degenerate" predicts the label, which is how a 43.7%/9.8% split in
    # the original BigVul build handed models a free shortcut.
    st = {}
    for prov in sorted({r["provenance"] for r in records}):
        for lab in (1, 0):
            g = [r for r in records
                 if r["provenance"] == prov and r["label"] == lab
                 and r.get("stub") is not None]
            if g:
                st[f"{prov}/{'vuln' if lab else 'safe'}"] = round(
                    sum(1 for r in g if r["stub"]) / len(g), 4)
    rep["stub_rate_by_label"] = st

    print("\n" + "=" * 68)
    print(f"  {rep['n_total']} CPGs | {rep['n_vulnerable']} vulnerable "
          f"({rep['prevalence']:.2%} prevalence)")
    print(f"  {rep['n_distinct_repos']} repositories | "
          f"{rep['n_distinct_commits']} commits | "
          f"{rep['n_distinct_pairs']} pair groups")
    print("=" * 68)
    if st:
        print("\n  stub rate by corpus/label (gap between labels = shortcut):")
        for k, v in st.items():
            print(f"    {k:22s} {v:.1%}")
        vs = [v for k, v in st.items() if k.endswith("/vuln")]
        ss = [v for k, v in st.items() if k.endswith("/safe")]
        if vs and ss:
            gap = abs(sum(vs)/len(vs) - sum(ss)/len(ss))
            print(f"    mean vuln-vs-safe gap: {gap:.1%}"
                  + ("" if gap < 0.05 else "   <-- INVESTIGATE"))

    print("\n  CWE-family support among vulnerable samples:")
    for f, n in fam.most_common():
        print(f"    {f:24s} {n:6d}{'' if n >= 500 else '   (thin)'}")
    print("\n  vulnerable samples with no family:")
    for k, n in noreason.most_common():
        print(f"    {k:24s} {n:6d}")
    print(f"\n  taxonomy covers {rep['coverage_of_typed']:.1%} of the "
          f"{len(typed)} CWE-carrying vulnerable samples")
    print(f"  families with >=500 real samples: "
          f"{len(rep['families_over_500'])}")
    if outside:
        print("\n  most common CWEs outside the taxonomy "
              "(candidates to add):")
        for k, n in outside.most_common(10):
            print(f"    {str(k):18s} {n}")
    return rep


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--skip-bigvul", action="store_true",
                    help="skip the slow 10.8GB CSV pass")
    a = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    if a.report_only:
        records = [json.loads(l) for l in OUT_JSONL.read_text().splitlines() if l]
    else:
        records: list[dict] = []
        print("[1/4] CVEfixes ...");  load_cvefixes(records)
        print("[2/4] Devign ...");    load_devign(records)
        if a.skip_bigvul:
            print("[3/4] BigVul ... SKIPPED")
        else:
            print("[3/4] BigVul (10.8GB CSV pass) ..."); load_bigvul(records)
        print("[4/4] BigVul re-sampled safe pool ..."); load_bigvul_safe_ext(records)
        with OUT_JSONL.open("w") as f:
            for r in records:
                f.write(json.dumps(r) + "\n")
        print(f"\n  wrote {OUT_JSONL}")

    OUT_REPORT.write_text(json.dumps(report(records), indent=2))
    print(f"  wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
